/* ---------- Dictionary ---------- */

const DICT: Record<LangCode, Record<string, string>> = {
  en: EN,
  ko: { ...EN, ...KO },
  ja: { ...EN, ...JA },
  zh: { ...EN, ...ZH },
  es: { ...EN, ...ES },
};

/* ---------- API ---------- */

/** Normalize any input to a valid LangCode */
export function coerceLanguage(input?: string | null): LangCode {
  if (!input) return "ko";
  const lower = input.toLowerCase().trim();

  // Direct match
  if (lower in DICT) return lower as LangCode;

  // Name-based matching
  const nameMap: Record<string, LangCode> = {
    korean: "ko", "한국어": "ko",
    english: "en",
    japanese: "ja", "日本語": "ja",
    chinese: "zh", "简体中文": "zh", "中文": "zh",
    spanish: "es", "español": "es",
  };

  return nameMap[lower] ?? "ko";
}

/** Translate a key with optional variable interpolation */
export function t(
  lang: LangCode | string | null | undefined,
  key: string,
  vars?: Record<string, string | number>
): string {
  const code = coerceLanguage(lang);
  const dict = DICT[code] ?? DICT.en;
  let result = dict[key] ?? EN[key] ?? key;

  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      result = result.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }

  return result;
}

/** localStorage key for language preference */
const LANG_STORAGE_KEY = "gamsa:lang";

/** Get stored language (or default ko) */
export function getStoredLang(): LangCode {
  if (typeof window === "undefined") return "ko";
  return coerceLanguage(localStorage.getItem(LANG_STORAGE_KEY));
}

/** Persist language choice */
export function setStoredLang(code: LangCode): void {
  if (typeof window === "undefined") return;
  localStorage.setItem(LANG_STORAGE_KEY, code);
}
